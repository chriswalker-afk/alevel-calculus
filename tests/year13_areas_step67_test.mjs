assert.match(understand,/Required area = area under A − area under B/);
assert.match(understand,/Only now choose an integration method/);
const index=fs.readFileSync(new URL('../src/index.html',import.meta.url),'utf8');
assert.match(index,/topic:y13:integration:areas/);
assert.match(index,/year13-areas\.css/);
console.log('Step 67 Year 13 area-technique contracts passed.');
