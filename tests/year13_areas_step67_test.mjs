import assert from 'node:assert/strict';
import fs from 'node:fs';
import { year13AreasTopic } from '../src/scripts/topic-content/year13-areas.js';
import { year13AreasLearningModes } from '../src/scripts/year13-areas-activities.js';
import { YEAR13_AREA_CASES, AREA_EXPLORER_SOURCE, AREA_METHOD_TAGS } from '../src/scripts/year13-areas-data.js';
import { INTEGRATION_AREA_POSITIVE_FUNCTIONS } from '../src/scripts/integration-area-model.js';
import { INTEGRATION_METHOD_TAGS } from '../src/scripts/trig-integration-data.js';
import { year13AreasAssessmentQuestionDefinitions } from '../src/scripts/question-definitions/year13-areas-assessment.js';
