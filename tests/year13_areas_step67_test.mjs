assert.ok(getMemoryItemsForTopic(year13AreasTopic.topicId).length>=4);
assert.ok(getMemoryGamePackForTopic(year13AreasTopic.topicId)?.sort);
assert.ok(getMemoryReviewPackForTopic(year13AreasTopic.topicId)?.mix);
