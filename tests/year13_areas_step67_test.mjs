assert.equal(year13AreasTopic.sequence,330);
assert.deepEqual(year13AreasTopic.modes,['understand','memorise','ao1','ao2','ao3']);
assert.ok(year13AreasTopic.activities.filter(a=>a.implementationStep===67).length>=19);
for(const mode of year13AreasTopic.modes) assert.ok(year13AreasLearningModes[mode].activities.length>0,`${mode} should have activities`);
assert.strictEqual(AREA_EXPLORER_SOURCE,INTEGRATION_AREA_POSITIVE_FUNCTIONS,'Step 67 must reuse the Step 27/46 AreaExplorer function-definition source by reference');
