assert.ok(YEAR13_AREA_CASES.some(x=>x.split===true),'A split-order case is required');
assert.ok(YEAR13_AREA_CASES.some(x=>x.geometry===true),'A geometry-vs-calculus case is required');
assert.equal(year13AreasAssessmentQuestionDefinitions.length,7);
